const contenedorCompetencias = document.getElementById('contenedor-competencias');
const botonesCat = document.querySelectorAll('.btn-cat');

function mostrarCompetencias(categoria, botonPulsado) {
    contenedorCompetencias.innerHTML = '';
    const lista = competenciasData[categoria];

    for (let i = 0; i < lista.length; i++) {
        const span = document.createElement('span');
        span.className = 'tag';
        span.textContent = lista[i];
        contenedorCompetencias.appendChild(span);
    }

    for (let i = 0; i < botonesCat.length; i++) {
        botonesCat[i].classList.remove('activo');
    }

    botonPulsado.classList.add('activo');
}

document.getElementById('btn-cat-desarrollo').addEventListener('click', function() {
    mostrarCompetencias('desarrollo', this);
});

document.getElementById('btn-cat-seo').addEventListener('click', function() {
    mostrarCompetencias('seo', this);
});

document.getElementById('btn-cat-diseno').addEventListener('click', function() {
    mostrarCompetencias('diseno', this);
});

document.getElementById('btn-cat-desarrollo').classList.add('activo');
mostrarCompetencias('desarrollo', document.getElementById('btn-cat-desarrollo'));